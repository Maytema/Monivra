// Every window and page the first application opens (openSheet, confirmAction, openPage call sites), so
// each can be matched with its native counterpart and looked at once on the emulator and in the old crawl.
// Usage: node tools/parity/windows.mjs > docs/architecture/PARITY_WINDOWS.md
import fs from "node:fs";
import path from "node:path";

const native = [];
const read = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) read(file);
    else if (/\.(tsx?|json)$/.test(entry.name) && !file.includes("i18n/ru")) native.push(fs.readFileSync(file, "utf8"));
  }
};
read("mobile/src");
const nativeText = native.join("\n");

// The text of a call from its opening parenthesis to the matching one (strings and templates skipped).
function callText(code, open) {
  let depth = 0;
  for (let i = open; i < code.length; i++) {
    const c = code[i];
    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      for (i++; i < code.length && code[i] !== quote; i++) if (code[i] === "\\") i++;
    } else if (c === "(") depth++;
    else if (c === ")" && --depth === 0) return code.slice(open, i + 1);
  }
  return code.slice(open);
}
const rows = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(file);
    else if (entry.name.endsWith(".js")) {
      const code = fs.readFileSync(file, "utf8");
      for (const m of code.matchAll(/\b(openSheet|confirmAction|openPage)\(/g)) {
        const text = callText(code, m.index + m[0].length - 1);
        const line = code.slice(0, m.index).split("\n").length;
        let label = "";
        if (m[1] === "openPage") label = (text.match(/\(\s*"([^"]+)"/) ?? [])[1] ?? "(computed)";
        else if (m[1] === "openSheet") label = [...text.matchAll(/,\s*"([A-Z][^"]+)"\s*,\s*"(?:dialog|sheet|menu)"/g)].map((x) => x[1]).pop() ?? [...text.matchAll(/"([A-Z][^"]{3,60})"/g)].map((x) => x[1]).pop() ?? "(computed)";
        else label = (text.match(/\(\s*(?:translate\w*\()?\s*"([^"]+)"/) ?? [])[1] ?? "(computed)";
        rows.push([m[1], label, `${file}:${line}`]);
      }
    }
  }
};
walk("js");
rows.sort((a, b) => a[0].localeCompare(b[0]) || a[2].localeCompare(b[2]));
console.log(`# Windows and pages of the first application\n\nGenerated by \`tools/parity/windows.mjs\`: ${rows.length} call sites. "Text in native" only says the label exists in the native source. Columns Native and Checked are filled by hand: the native file/screen, and the screenshot pair that was compared (or "adapted: reason").\n`);
console.log("| Kind | Label | Old place | Text in native | Native | Checked |\n|---|---|---|---|---|---|");
for (const [kind, label, place] of rows) console.log(`| ${kind} | ${label.replace(/\|/g, "/")} | ${place} | ${label === "(computed)" ? "?" : nativeText.includes(label) ? "yes" : "**no**"} |  |  |`);
console.log(fs.readFileSync("tools/parity/windows-notes.md", "utf8"));
