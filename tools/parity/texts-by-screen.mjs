// For every file of the first application's screens: which of its translated texts the native source lacks.
// Usage: node tools/parity/texts-by-screen.mjs > docs/architecture/PARITY_TEXTS.md
import fs from "node:fs";
import path from "node:path";
import { russianStrings } from "../../js/i18n/ru.js";

const native = [];
const read = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) read(file);
    else if (/\.(tsx?|json)$/.test(entry.name) && !file.includes("i18n/ru")) native.push(fs.readFileSync(file, "utf8"));
  }
};
read("mobile/src");
const nativeText = native.join("\n");
const present = (key) => nativeText.includes(key) || nativeText.includes(key.slice(0, 40));

const rows = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(file);
    else if (entry.name.endsWith(".js")) {
      const code = fs.readFileSync(file, "utf8");
      const used = Object.keys(russianStrings).filter((key) => code.includes(JSON.stringify(key)) || code.includes(`'${key}'`) || code.includes(`"${key}"`) || code.includes("`" + key + "`"));
      if (used.length) rows.push([file, used, used.filter((k) => !present(k))]);
    }
  }
};
walk("js/screens");
walk("js/ui");
const total = rows.reduce((n, r) => n + r[1].length, 0);
const missing = rows.reduce((n, r) => n + r[2].length, 0);
console.log(`# Texts of the first application's screens that the native source lacks\n\nGenerated by \`tools/parity/texts-by-screen.mjs\`. ${missing} of ${total} usages missing. A missing text is either to be added, or browser-only (decide and note it below).\n`);
for (const [file, used, lost] of rows.sort((a, b) => b[2].length - a[2].length)) {
  if (!lost.length) continue;
  console.log(`## ${file} — ${lost.length} of ${used.length}\n`);
  for (const key of lost) console.log(`- ${key.replace(/\n/g, " ").slice(0, 150)}`);
  console.log("");
}
